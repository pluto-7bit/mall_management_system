--    ⚠️ 这几个是【整个库】的统计，不是本次改动的统计 ——
--       真正要确认的是「没有封面的商品数」必须是 0。
--
--    ★ 最后那条「重名商品」必须为空。product 表【没有】name 唯一索引，
--      所以这个脚本重复执行不会报错，只会静默地插出同名商品 ——
--      这三条 SELECT 是唯一能发现那件事的地方。
