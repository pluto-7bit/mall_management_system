-- ============================================================================
-- 迁移脚本 08b：把 orders 的幂等唯一索引从「全局唯一」改成「按会员唯一」
-- ============================================================================
--
-- 背景
-- ----
-- migration-08-order.sql 里给 idempotency_key 建的是【列级】唯一索引：
--
--     UNIQUE KEY uk_idempotency_key (idempotency_key)
--
-- 意思是「全库所有订单里，这个键只能出现一次」。
-- 这个约束【太强了】，而且强错了地方。
--
-- 为什么不对
-- ----------
-- 幂等的作用域应该跟着「谁在重复提交」走。这里的「谁」是会员，
-- 所以唯一性应该是「同一个会员的订单里，这个键只能出现一次」。
-- 列级唯一索引做不到这一点，会带来两个真实问题：
--
--   1. 【不同会员之间会互相干扰】
--      幂等键是客户端生成的。10 个不同会员的浏览器，
--      生成出同一个键的概率虽然低，但一旦撞上，
--      后下单的那个会员会直接失败 —— 而他什么都没做错。
--
--   2. 【更严重：可以被人为构造】
--      幂等键是客户端说了算的，那么 A 只要抢先提交订单、
--      把某个键占住，B 用同样的键就永远下不了单。
--      这是「用一个用户能控制的值去影响另一个用户」，
--      是典型的越权类问题（虽然这里是 DoS 不是读数据）。
--      攻击者甚至不需要知道 B 会用什么键，随机乱占就行 ——
--      占满一个键的代价只是下一次单。
--
-- ★ 提炼出来的规则：
--   【幂等的作用域 = 幂等主体 + 幂等键，所以唯一索引必须包含主体 id。】
--   只对「键」本身建唯一索引，等于把不同用户的命名空间混在了一起。
--
-- 改法
-- ----
-- 换成组合唯一索引 (member_id, idempotency_key)：
--   - 同一个会员重复提交同一个键 → 撞唯一索引 → 被拦下（这才是我们要的）
--   - 不同会员用同一个键         → 不冲突，各下各的
--
-- ⚠️ 为什么现在改代价这么低？
--    因为 orders 表还是空的（订单功能刚写，一条数据都没有）。
--    表一旦有数据，换唯一索引就要先检查存量数据会不会撞车。
--    【约束类的东西，越早定对越便宜。】这也是为什么它值得单独一个迁移脚本、
--    而不是等「以后有空再说」。
--
-- 执行方式
-- --------
--   "C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe" -u root -p123456 mall < migration-08b-idempotency-scope.sql
--
-- 执行后验证（应该看到 uk_member_idempotency，且没有 uk_idempotency_key）：
--   SHOW INDEX FROM orders;
-- ============================================================================

USE mall;

-- 先确认表是空的。有数据的话这个改动需要先评估存量重复情况，先停下来看一眼。
SELECT COUNT(*) AS '改动前的订单数（必须是 0）' FROM orders;

ALTER TABLE orders DROP INDEX uk_idempotency_key;

ALTER TABLE orders
    ADD UNIQUE KEY uk_member_idempotency (member_id, idempotency_key);

-- ---------------------------------------------------------------------------
-- 验证
-- ---------------------------------------------------------------------------
SELECT INDEX_NAME, SEQ_IN_INDEX, COLUMN_NAME, NON_UNIQUE
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = 'mall'
  AND TABLE_NAME = 'orders'
ORDER BY INDEX_NAME, SEQ_IN_INDEX;
