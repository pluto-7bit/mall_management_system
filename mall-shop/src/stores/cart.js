import { ref } from 'vue'
import { defineStore } from 'pinia'
import { addCartItem, getCartCount } from '@/api/cart'

/**
 * 购物车的<b>全局</b>状态。
 *
 * <h3>★ 为什么这里只存「件数」，不存整个购物车？</h3>
 *
 * <p>因为要区分「全局共享的状态」和「页面自己的状态」：
 *
 * <pre>
 *   件数（count）   → 导航栏角标要显示，【每个页面】都要用 → 放 store
 *   商品列表        → 只有购物车页面关心                    → 放页面组件里
 * </pre>
 *
 * <p>把所有东西都塞进 store 是个常见的坏习惯。store 是全局单例，
 * 放进去的东西<b>生命周期会变得不明确</b>：
 * 组件卸载了它还在，什么时候该清、什么时候该刷新都说不清楚。
 * 判断标准很简单：<b>「这个数据有第二个页面要用吗？」</b>
 * 没有就别放 store。
 *
 * <p>件数放 store，具体内容留在 {@code Cart.vue} 里 ——
 * 这样购物车页每次进来都重新拉最新数据，天然避免了
 * 「store 里是旧数据，和服务器不一致」的问题。
 *
 * <h3>★ 角标是怎么保持同步的？</h3>
 *
 * <p>没有用轮询，也没有用 WebSocket。做法是：
 * <b>任何会改变购物车的操作，成功后都手动调一次 refresh()。</b>
 * 也就是「写操作负责通知」。
 *
 * <p>这么做的前提是「购物车的所有写入口都在这个前端里」——
 * 对单端应用成立。如果以后有了小程序、App，
 * 用户在 App 里加了购，网页端的角标不会更新。
 * 到那时候才需要轮询或者推送。<b>现在不做的理由是需求还不存在，
 * 而不是「这个方案更先进」。</b>
 */
export const useCartStore = defineStore('cart', () => {
  // ---------------------------------------------------------------------------
  // state
  // ---------------------------------------------------------------------------

  /** 购物车里的商品总件数（不是条目数）。0 表示空 */
  const count = ref(0)

  /** 正在请求中 —— 用来给按钮加 loading，防止连点造成重复加购 */
  const loading = ref(false)

  // ---------------------------------------------------------------------------
  // actions
  // ---------------------------------------------------------------------------

  /**
   * 从服务端拉取最新的件数。
   *
   * <p>★ 未登录时<b>直接置 0 并返回，不发请求</b>。
   * 因为购物车接口需要登录，游客调用必然 401，
   * 而 {@code request.js} 的拦截器遇到 401 会「清 token + 跳登录页」——
   * 那就会变成「游客一打开首页就被弹去登录页」。
   * 这个判断就是为了避免那个灾难性的体验。
   *
   * <p>这是个<b>很容易漏掉的地方</b>：一个全局的、每个页面都会调的请求，
   * 如果不判断登录状态，就会把「未登录」这个正常状态
   * 变成一个异常流程。
   */
  async function refresh(isLoggedIn) {
    if (!isLoggedIn) {
      count.value = 0
      return
    }
    try {
      // ★ 后端返回的是一个纯数字（比如 5），
      //   request.js 的拦截器已经把外层的 {code, message, data} 剥掉了，
      //   所以这里拿到的就是数字本身
      const n = await getCartCount()
      count.value = Number(n) || 0
    } catch {
      // ★ 拉角标失败【不弹提示、不改变现有值】。
      //
      //   理由：角标只是个装饰性的提示，它更新失败不该打扰用户。
      //   如果这里弹一个「获取购物车数量失败」的红条，
      //   用户会以为是自己的操作出了问题，实际上他什么都没干。
      //
      //   ★ 一条通用原则：**装饰性数据的加载失败，应该静默降级。**
      //     反之，用户主动触发的操作失败了就必须明确告诉他 ——
      //     因为他在等结果。
      //
      //   这里保留 count 的原值（不清零）也是同样的考虑：
      //   把一个「3」变成「0」比让它暂时停在「3」更糟，
      //   前者看起来像是「购物车被清空了」。
    }
  }

  /**
   * 加入购物车（带 loading 保护）。
   *
   * <p>★ 把 loading 放在 store 里而不是组件里，是为了防连点：
   * 用户在详情页快速点三下「加入购物车」，如果三下都发出去，
   * 就会加三次（因为 quantity 是增量语义）。
   *
   * <p>注意这只是<b>前端</b>的防护，绕过页面直接调接口依然能连加三次 ——
   * 但那不是 bug，加三次本来就该是三次。
   * 真正需要防的「重复提交」在<b>下单</b>场景（里程碑 8），
   * 那里必须由后端保证，因为涉及钱。
   *
   * @returns {Promise<boolean>} 成功返回 true，失败返回 false（不抛异常）
   */
  async function add(productId, quantity = 1) {
    if (loading.value) {
      return false
    }
    loading.value = true
    try {
      await addCartItem(productId, quantity)
      return true
    } catch {
      // 错误提示已由 request.js 统一弹出，这里只负责返回结果
      return false
    } finally {
      loading.value = false
    }
  }

  /**
   * 重置（退出登录时调用）。
   *
   * <p>★★ <b>这一句是这个 store 存在的最重要理由之一。</b>
   *
   * <p>购物车数据在 Redis 里按会员 id 归属，退出登录不该删它 ——
   * 换台设备登录还要能看到。但<b>前端 store 里缓存的件数必须清掉</b>，
   * 否则下一个在这台电脑上登录的人（比如宿舍共用的电脑），
   * 会看到上一个人的购物车角标，甚至能直接看到内容。
   *
   * <p>购物车内容是存在内存里的，退出后跳首页时组件会销毁，所以
   * 内容不用担心。但 store 是全局单例，<b>它不会因为页面切换而清空</b>，
   * 必须手动清。
   *
   * <p>这类「登出时要清理什么」的清单，是多人共用设备时最容易出事的地方。
   * 判断方法：<b>问自己「上一个人的什么信息会留在屏幕上？」</b>
   */
  function reset() {
    count.value = 0
    loading.value = false
  }

  return {
    count,
    loading,
    refresh,
    add,
    reset,
  }
})
