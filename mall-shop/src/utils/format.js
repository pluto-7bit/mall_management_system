/**
 * 展示用的格式化工具。
 *
 * <h3>★ 这个文件为什么存在？</h3>
 *
 * <p>因为「金额保留两位小数」这件事，在这个项目里被就地写过<b>四次</b>：
 * <pre>
 *   1. 购物车的「选中合计」—— 内联在 selectedAmount 这个 computed 里
 *   2. 结算页的模板内联
 *   3. 收银台自己的一个本地 formatAmount 函数
 *   4. 「我的订单」页 —— 第四处
 * </pre>
 *
 * <p>前三处写下来的时候，每一处都只写了「要保留两位小数」，
 * 没有一处写了「这件事已经有人做过了」。到第四处才提出来，
 * 判据是收银台当年留在自己注释里的那句话：
 * <b>「三份重复已经到临界点了 —— 如果出现第四处，就该把它提到
 * {@code utils/} 里去了。」</b>
 *
 * <h3>★ 为什么是「第四处」而不是「第二处」？</h3>
 *
 * <p>因为抽函数本身也有成本：多一个文件、多一层跳转、
 * 将来改的时候要多想一步「还有谁在用」。
 * 两处重复时，那个成本很可能比收益大；等到第四处，
 * 「改一处漏三处」的风险就明显更贵了。
 * <b>重复多少次才值得抽象，取决于每次重复的代价，而不是一个固定数字</b>——
 * 这里的代价是「金额显示不一致」，用户会以为算错了钱。
 *
 * <h3>★ 收口是分两次做完的，第二次是单独一轮</h3>
 *
 * <p>提出这个文件的那一轮（里程碑 10）<b>只改了收银台和「我的订单」两处</b>。
 * 购物车和结算页那两份被<b>故意留着</b>，理由不是"懒得改"：
 * 它们不是独立函数，而是分别内联在一个 computed 和一个模板里 ——
 * 动它们等于去动别的逻辑依赖着的东西。
 * 这正是项目里那条被反复引用的纪律：
 * <b>顺手改掉别人依赖的东西，是协作里最招人烦的一类改动。要改就单独一轮、单独说明。</b>
 *
 * <p>里程碑 14 就是那一轮。四份现在只剩这一份，而且是一份
 * <b>从调用点上就看得出来</b>的：mall-shop 里每一处显示金额的 {@code ¥} 后面，
 * 都跟着这个函数的名字。购物车那两个 computed 也不再返回格式化好的字符串 ——
 * 它们回答「多少钱」，怎么写由各自页面的模板决定。
 *
 * <p>⚠️ 注意本轮修的<b>不只是"实现重复"，还有"绕过"</b>：
 * 当时另有 4 处金额<b>根本没走任何格式化</b>，直接就把后端的数字印出来了。
 * 只把 4 份实现合成 1 份、却让这 4 处继续绕过它，用户看得见的那个 bug
 * 会活过整轮"清账"。
 *
 * <h3>⚠️ 这个文件的开头原来有一张表，表里写着「文件名:行号」</h3>
 *
 * <p>现在一个行号都没有了，只写函数名和它做的事。原因是那张表<b>腐烂过</b>：
 * 它引用的位置里，有的在下一轮就被删掉了（收银台那个本地函数）、
 * 有的移了位，于是注释指向的是空行和别的东西 —— 而清理它花掉了里程碑 14 的一部分时间。
 *
 * <p>★ 所以这里立一条<b>只对这份文档有效</b>的写法：
 * <b>要说清"哪段代码"时，写它的名字和语义，不写它在第几行。</b>
 * 名字改了至少还会报错、还搜得到；行号只会安静地失效，
 * 而<b>一条安静失效的引用，比没有引用更坏</b> ——
 * 它会让人以为自己看过了那段代码。
 * （项目里其它地方还有写行号的注释 —— 那是个更大的话题，不在这里顺手改。）
 *
 * <h3>★ 为什么不干脆让后端把金额序列化成字符串？</h3>
 *
 * <p>那样 {@code 228.70} 会原样到达前端、尾随的 0 不会丢，
 * 这个函数看起来就不需要了。不这么做有两个理由：
 *
 * <ol>
 *   <li><b>前端仍然需要一个。</b> 购物车的「选中合计」和结算页的「预估合计」
 *       是前端把后端给的每条小计<b>相加</b>出来的（后端没有这个数，
 *       因为它是"用户勾选出来的"）。{@code 9.90 * 3} 在 JS 里是
 *       {@code 29.700000000000003} —— 金额变成字符串也照样要过一遍格式化。</li>
 *   <li><b>那是一次影响所有接口的契约改动。</b> 全部金额字段的形状会从数字变成字符串，
 *       而 {@code test-frontend-contract.py} 里钉着「totalAmount 能当数字用」，
 *       前端所有 {@code Number(...)} 兜底、比较、求和都要重新想一遍。
 *       <b>为了一个纯粹的显示问题去动所有接口的形状，是拿最贵的东西换最便宜的收益。</b></li>
 * </ol>
 *
 * <p>换句话说：<b>「后端该怎么传」是后端的事；这个文件只管"拿到数之后怎么印"。</b>
 */

/**
 * 金额显示：保留两位小数。
 *
 * <p><b>★ 这不是"好看一点"，是必需。</b>
 *
 * <p>后端 {@code BigDecimal} 的 {@code 228.70} 在 HTTP 响应原文里是
 * {@code "price":228.70} —— <b>那个尾随的 0 本来是有的</b>（实测过）。
 * 但 JSON 的数字就是数字：{@code JSON.parse('228.70')} 得到的是
 * JS 的 number {@code 228.7}，<b>「它原本有两位小数」这条信息就没了</b>。
 * 于是 {@code ¥{{ item.price }}} 渲染出来是「¥228.7」，
 * 而同一页上用这个函数算的合计写着「¥228.70」——
 * <b>同一笔钱在两个位置长得不一样</b>，用户会以为哪里算错了。
 *
 * <p>⚠️ 所以这个函数的存在是<b>为了让「同一笔钱到处长得一样」</b>，
 * 而不是为了"格式漂亮"。理解了这一点，就知道它为什么必须只有一份 ——
 * 两份格式化函数就有两个答案，而它们服务的本来是同一个数字。
 *
 * <p>★ 它修两样东西，一件也不能少：
 * 尾随的 0（{@code 228.70 → 228.7}），和浮点误差
 * （{@code 9.90 * 3 → 29.700000000000003}）。
 * 它<b>不能</b>修的是「这个数本身算错了」—— 数字从哪来是别人的事。
 *
 * <h3>★ 顺带说清边界：前端算的钱永远是显示，不是真相</h3>
 *
 * <p>真正的金额是后端用 {@code BigDecimal} 算好、存在
 * {@code DECIMAL(10,2)} 里的，这里做的是把那个数原样印出来。
 * 所以哪怕这里格式化错了，也不会让用户少付或多付一分钱。
 * <b>前端碰钱的地方，判断标准永远是「它会不会改变发出去的金额」——
 * 这个函数不会，所以它是安全的。</b>
 *
 * <p>（对比 {@code Checkout.vue} 里算合计的逻辑：那个也不会 ——
 * 提交给后端的只有商品 id 和地址，金额由后端重算。
 * 判断标准是同一句。）
 *
 * <h3>⚠️ 谁能守住这个函数？别写不存在的东西</h3>
 *
 * <p><b>这个项目的前端没有单元测试</b>（两个 {@code package.json} 里都没有
 * vitest / jest / playwright 之类的框架）。所以「有测试盯着它」这种话
 * 在这里不能随手写 —— 它听起来很合理，但它是一句<b>可以核实</b>的话，
 * 而核实的结果是假的。（这句话以前真的写在这个文件附近，里程碑 14 一并清掉。）
 *
 * <p>真正盯着它的只有两样：
 * <ol>
 *   <li>{@code sql/test-frontend-format.py} —— 静态检查：mall-shop 里
 *       {@code toFixed(2)} 只允许出现在这一个文件里，
 *       且每一处显示金额的 {@code ¥} 后面都必须出现这个函数；</li>
 *   <li>浏览器验收（{@code tools/shot.py} 的 {@code --eval}）—— 读页面上真实的文字。</li>
 * </ol>
 * ⚠️ 注意这两样<b>都不检查这个函数的内部实现</b>。
 * 它们检查的是「还有没有第二份」「还有没有绕过去的」——
 * 也就是这个文件存在的全部理由。
 *
 * @param {number|string|null|undefined} v 后端给的金额（JSON 数字，可能是 null）
 * @returns {string} 形如 "228.70" 的字符串，<b>不带货币符号</b>
 *                   （符号由各页面自己加：¥ 还是 $ 是界面的事）
 */
export function formatAmount(v) {
  // ★ 用 Number(v || 0) 而不是 Number(v)：
  //   null / undefined / '' 都该显示成 0.00，而不是 NaN。
  //   后端配了 non_null，null 字段在 JSON 里直接消失 ——
  //   所以在 JS 这边读到的就是 undefined，这是一个【正常】的情况。
  //
  // ⚠️ 参数类型【不要】收窄成 number。虽然现在每个调用点传的都是数字，
  //   但"从 JSON 里读出来的金额一定是 number"这件事并没有被任何东西保证。
  //   Number() 这一层兜底的成本是零，去掉它换不来任何东西。
  //
  // ⚠️ 也【不要】给它加第二个参数（比如 fallback）。「查不到价格意味着什么」
  //   是各个页面的语义，不是金额格式化的问题 —— 购物车失效商品那一行
  //   要显示破折号，那个判断写在那边的模板里。
  //   为了让一个调用者少写几个字符给共享函数加模式开关，
  //   正是在犯这个文件当初要清掉的那类错。
  return Number(v || 0).toFixed(2)
}
