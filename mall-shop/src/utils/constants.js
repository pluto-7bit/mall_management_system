/**
 * 前端的业务常量。
 *
 * <h3>★ 为什么这个文件里只有一个常量？</h3>
 *
 * <p>因为它<b>本该只有一个</b>。前端真正需要知道的业务规则很少 ——
 * 绝大多数规则（库存够不够、能不能下单、金额怎么算、谁是默认地址）
 * 都在服务端，前端只负责把结果显示出来。
 *
 * <p>一旦这个文件开始变长，通常说明有问题：
 * 要么是把该放后端的规则抄到了前端（两份规则迟早不一致），
 * 要么是把纯展示的东西（列宽、分页大小）放了进来
 * （那些是各个页面自己的事，不该全局共享）。
 *
 * <p>所以这里只放<b>「不去抄一遍就没法把界面做对」</b>的那类常量。
 */

/**
 * 单个商品一次最多能买几件。
 *
 * <p>★ <b>这是从后端抄过来的</b>，对应
 * {@code com.example.mall.common.BusinessRules.MAX_QUANTITY_PER_ITEM}。
 *
 * <h4>为什么非要抄</h4>
 *
 * <p>因为不抄的话界面会自相矛盾。举个真实的例子：
 * 一件库存 500 的商品，商品详情页的数量选择器上限绑的是库存
 * （也就是 500），用户能一路选到 200 ——
 * <ul>
 *   <li>点「加入购物车」→ 后端压到 99 并返回 1008</li>
 *   <li>点「立即购买」→ 提交订单时报「最多购买 99 件」</li>
 * </ul>
 * 用户看到库存写着 500、自己只选了 200，却被拒绝，会认为系统坏了。
 * <b>界面允许的操作和系统允许的操作不一致，就是一种 bug。</b>
 *
 * <h4>抄它的代价，以及怎么兜底</h4>
 *
 * <p>代价很实在：<b>后端哪天把 99 改成 10，这里就过时了。</b>
 * 前端读不到 Java 常量，这个重复用代码消除不掉。能做的只有两件事：
 * <ol>
 *   <li>把对应关系写清楚（就是上面那行全限定类名），
 *       改后端的人搜 {@code MAX_QUANTITY_PER_ITEM} 时能一起搜到</li>
 *   <li>让后端的拒绝信息<b>带上具体数字</b> ——
 *       见 {@code OrderServiceImpl} 里那句「最多购买 99 件」。
 *       这样即使前端抄的值过时了，用户看到的仍然是准确的信息</li>
 * </ol>
 *
 * <p><b>★ 凡是抄来的常量，都必须留一条「抄错了会怎样」的退路。</b>
 * 抄的时候只想着"反正现在是对的"，过时就变成最难查的那类 bug：
 * 两边各自看都合理，合起来才矛盾。
 */
export const MAX_QUANTITY_PER_ITEM = 99
