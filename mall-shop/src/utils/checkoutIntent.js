/**
 * 「一次下单意图」的身份 —— 幂等键的生成与保管。
 *
 * <h2>背景：幂等键是干什么的</h2>
 *
 * <p>用户点「提交订单」→ 请求发出去了 → <b>网络卡住，用户看不到结果</b>。
 * 这时他会怎么办？再点一次。于是服务端收到两个一模一样的请求。
 *
 * <p>后端的解法是：<b>客户端给「一次下单意图」编个号</b>（这就是幂等键），
 * 服务端记住这个号，第二次收到同一个号就直接把上次那笔订单还回去，
 * 不再建新单。详见后端 {@code OrderBaseDTO.idempotencyKey} 的注释。
 *
 * <p>但后端的这套机制<b>能不能生效，完全取决于前端怎么生成这个键</b>。
 * 生成错了，保护就是零 —— 而且错得很隐蔽，因为接口看起来"有幂等保护"。
 *
 * <h2>★ 我一开始的想法是错的，记在这里</h2>
 *
 * <p>最初的设计是「<b>进入结算页时</b>生成一个随机键，放在组件里」。
 * 听起来没问题，但它有一个致命的漏洞：<b>组件里的变量活不过一次刷新。</b>
 *
 * <p>把最危险的那个场景走一遍：
 * <pre>
 *   1. 用户点「提交订单」
 *   2. 请求发出去了，服务端其实已经建好了订单（库存扣了、订单落了库）
 *   3. 但响应迟迟没回来（网络慢、或者用户等得不耐烦）
 *   4. 用户按了 F5 —— 【页面重新挂载，生成一个新的随机键】
 *   5. 用户再点「提交订单」
 *   6. 服务端看到的是一个全新的键 → 建了第二笔订单
 * </pre>
 * 用户买了一件东西，付了两笔钱。<b>幂等保护在这个流程里一次都没起作用，
 * 而它看起来明明是"实现了"的。</b>
 *
 * <p>根因是「意图的身份」被存进了一个<b>生命周期太短的地方</b>。
 * 判断一个状态该存哪，标准不是"用起来方不方便"，而是
 * <b>「它该活多久」</b>：
 * <pre>
 *   组件里的变量   →  活到组件卸载 / 页面刷新。太短 ✗
 *   sessionStorage →  活到这个标签页关闭。刚好 ✓
 *   localStorage   →  活到天荒地老。太长 ✗（见下面 TTL 那段）
 * </pre>
 *
 * <h2>★ 光"记住"还不够：键要绑定「这次买的是什么」</h2>
 *
 * <p>如果只是把键存进 sessionStorage，会冒出另一个 bug：
 * 用户<span>正常地</span>在同一件商品上下了两单（比如先买 1 个，
 * 过一会儿又想再买 1 个）—— 第二个请求会带着<b>同一个键</b>，
 * 服务端认为"这个我处理过了"，把第一笔订单还给他。
 * <b>第二笔订单永远不会被创建，而且没有任何报错。</b>
 *
 * <p>所以存的不只是键，还有配套的「<b>签名</b>」——
 * 把「买什么」这件事压成一个字符串。规则是：
 * <pre>
 *   进来时算一次签名：
 *     和存着的一样  →  这是同一次意图（很可能是刷新了页面）→ 【复用】原来的键
 *     和存着的不一样 →  这是新的一次意图（用户改了东西）    → 【新生成】一个键
 * </pre>
 *
 * <p>⚠️ 注意签名<b>只包含「买哪些商品、各买几件」</b>，
 * 不含收货地址、不含备注。为什么？
 *
 * <p>因为「改地址」和「重新下单」是两件事。
 * 用户提交后发现地址选错了、改一下再提交，
 * 这<b>仍然是同一次购买行为</b>，不是想买两份。
 * 如果地址进了签名，就会生成新的键 ——
 * 万一第一笔其实已经成功了（还是那个"响应丢了"的场景），
 * 改个地址再提交就变成了第二笔订单。
 *
 * <p>（那用同一个键提交、服务端返回的是<b>老地址</b>的那笔订单怎么办？
 * 这是对的，甚至是必要的：那笔订单<b>已经存在了</b>，
 * 库存已经扣了、货可能已经在拣了。这时候"改地址"本来就该走
 * 「修改订单地址」的流程，而不是"假装刚才那单不存在"。
 * 幂等返回旧订单，等于诚实地告诉用户："这一单我之前已经收下了。"）
 *
 * <h2>★ 还要有个过期时间（TTL）</h2>
 *
 * <p>成功下单之后我们会把记录删掉。但如果<b>删的那一步没执行到</b>呢？
 * （标签页崩了、用户强杀了浏览器）——记录就会一直留在 sessionStorage 里，
 * 直到这个标签页关闭。
 *
 * <p>留着会怎样？用户半小时后用同一个标签页、买同样的东西，
 * 签名一致 → 复用旧键 → 服务端认出"处理过" → <b>返回半小时前那笔订单，
 * 而这一次的购买根本没发生。</b>用户会以为下单成功，其实没有。
 *
 * <p>所以再加一道时间闸：<b>超过 30 分钟的记录视为过期，重新生成键。</b>
 *
 * <p>⚠️ 这是一个<b>权衡</b>，不是"越严越好"：
 * <pre>
 *   TTL 太长  →  陈旧记录可能吃掉一次真实的下单（就是上面那段）
 *   TTL 太短  →  用户提交卡住、等了很久再重试时，保护已经失效 → 重复下单
 * </pre>
 * 30 分钟的依据是：请求本身的超时只有 10 秒
 * （见 {@code api/request.js} 的 {@code timeout}），
 * 用户从打开结算页到放弃，正常也就几分钟。
 * 30 分钟足够覆盖"响应丢了、用户反复重试"的真实窗口，
 * 又远小于"用户半个小时后重新想起来买东西"的间隔。
 *
 * <p><b>★ 一个数字背后的权衡，必须写下来。</b>
 * 不写的话，下一个人看到 30 只会想"随便定的吧"，然后随手改成 1 天。
 */

/** sessionStorage 的 key。加前缀避免和别的项目/页面撞名 */
const STORAGE_KEY = 'mall_checkout_intent'

/** 记录超过这个时间就作废，理由见文件头那段权衡 */
const TTL_MS = 30 * 60 * 1000

/**
 * 生成一个符合后端格式要求的幂等键。
 *
 * <p>后端的约束是 {@code ^[A-Za-z0-9_-]{8,64}$}
 * （见 {@code OrderBaseDTO}）—— 只能有字母、数字、下划线、连字符。
 * <b>这个约束不是随便定的</b>：幂等键会被写进数据库、
 * 出现在日志里、可能被拼进 URL，限制字符集能省掉一堆转义问题。
 *
 * <p>优先用 {@code crypto.randomUUID()}。它是浏览器提供的
 * 密码学安全随机数，而且 UUID v4 的碰撞概率可以忽略。
 *
 * <p>⚠️ {@code crypto.randomUUID} 只在<b>安全上下文</b>
 * （https 或 localhost）里可用。开发环境是 localhost，所以有；
 * 但如果哪天部署到 http 的测试机上，它会变成 undefined，
 * 于是下面那个兜底分支就必须存在 ——
 * <b>"我这儿能跑"不等于"到处都能跑"。</b>
 */
function randomKey() {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID()
  }
  // 兜底：36 进制随机串。Math.random 不是密码学安全的，
  // 但对"两个用户恰好生成同一个键"这个场景，36 进制的 13 位
  // 已经绰绰有余（何况唯一索引是 (member_id, 幂等键)，
  // 需要同一个会员自己撞上自己才算冲突）
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`
}

/**
 * 算出「这次买的是什么」的签名。
 *
 * <p>入参是一组 {@code "商品id:数量"}，顺序无关
 * （用户勾选的先后顺序不该被当成两次不同的意图），
 * 所以这里<b>先排序再拼接</b>。
 *
 * <p>⚠️ 必须排序。不排序的话，同一批商品换个勾选顺序就会算出
 * 不同的签名 → 生成新的键 → 幂等保护失效。
 * 这类"看起来等价的东西算出来不等价"是签名/哈希最经典的坑。
 *
 * @param {Array<{productId: number, quantity: number}>} lines
 * @returns {string}
 */
export function signatureOf(lines) {
  const parts = lines
    .map((l) => `${l.productId}:${l.quantity}`)
    .sort()
  return parts.join(',')
}

/**
 * 拿到「本次下单意图」的幂等键。
 *
 * <p>这是这个模块对外的<b>唯一入口</b>。调用方（结算页）只需要
 * 告诉它「我要买这些」，它负责决定是复用还是新生成。
 * 让调用方自己判断该不该复用，就等着出现"两个地方判断得不一样"。
 *
 * @param {Array<{productId: number, quantity: number}>} lines
 * @returns {string} 幂等键
 */
export function getIntentKey(lines) {
  const signature = signatureOf(lines)

  const saved = readRecord()
  if (saved && saved.signature === signature && !expired(saved)) {
    // ★ 同一次意图（最典型的场景就是用户刷新了页面）—— 复用原来的键。
    //   这就是"防住重复下单"真正起作用的那一步：
    //   刷新前和刷新后拿到的是【同一个键】，服务端才能认出这是重复提交。
    return saved.key
  }

  const key = randomKey()
  writeRecord({ signature, key, at: Date.now() })
  return key
}

/**
 * 一次下单成功后调用它，忘掉这次意图。
 *
 * <p>★ <b>不清掉这个记录，就是上面 TTL 那段说的那个 bug</b>：
 * 用户想再买一份同样的东西，结果被服务端当成重复提交，
 * 把上一笔订单还回来 —— 购买没有发生，但界面显示成功。
 *
 * <p>⚠️ 所以这一步要放在「拿到成功响应」之后立即执行，
 * 而且不能被任何分支绕过。<b>成功路径上的清理，
 * 和失败路径上的清理一样重要 —— 后者只是脏一点，前者会出错。</b>
 */
export function clearIntent() {
  try {
    sessionStorage.removeItem(STORAGE_KEY)
  } catch {
    // sessionStorage 在某些隐私模式下会抛异常。
    // 清不掉只是脏一点（最多是那 30 分钟的 TTL 兜底），
    // 绝不能让"清理失败"变成一个下单失败的报错
  }
}

// ---------------------------------------------------------------------------
// 内部：读写 sessionStorage
// ---------------------------------------------------------------------------

function readRecord() {
  try {
    const raw = sessionStorage.getItem(STORAGE_KEY)
    if (!raw) return null
    const parsed = JSON.parse(raw)
    // ★ 校验形状再使用。sessionStorage 里的东西是【字符串】，
    //   可能是别人（别的页面、上一版代码）写进去的，
    //   也可能是手工改的。直接 JSON.parse 后当成对象用，
    //   遇到坏数据就会在渲染或请求里炸开 —— 而且报错的地方
    //   离真正的原因很远，很难查
    if (typeof parsed?.key !== 'string' || typeof parsed?.signature !== 'string') {
      return null
    }
    return parsed
  } catch {
    // 坏了就当没有。重新生成一个键即可，不影响功能
    return null
  }
}

function writeRecord(record) {
  try {
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify(record))
  } catch {
    // 写不进去（隐私模式 / 配额满）就退化成"每次进来都新生成一个键"，
    // 也就是回到我一开始那个有漏洞的设计。功能还能用，
    // 只是防不住刷新导致的重复提交 —— 比整个下单流程报错好得多
  }
}

function expired(record) {
  return Date.now() - record.at > TTL_MS
}
