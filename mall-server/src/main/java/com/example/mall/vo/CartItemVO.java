package com.example.mall.vo;

import lombok.Data;

import java.math.BigDecimal;

/**
 * 购物车里的<b>一条</b>商品。
 *
 * <h3>★ 这个 VO 的字段来自两个不同的地方，这是个关键设计</h3>
 *
 * <pre>
 *   skuId、数量      ← 来自 Redis（这是购物车【真正存】的东西）
 *   名称、价格、库存
 *   规格文本、商品 id ← 来自 MySQL（购物车【不存】，每次现查）
 * </pre>
 *
 * <p>★ 里程碑 15 阶段 4：Redis 里存的那个 id 从商品换成了规格。
 * 这不是改个名字 —— <b>它是「一件商品在购物车里占几行」的答案</b>：
 * 换成 skuId 之后，「黑色 S」和「白色 M」是两行，各自有自己的数量。
 *
 * <p>为什么价格不存进 Redis？因为<b>价格必须以数据库为准</b>。
 *
 * <p>想象一下如果购物车存了价格：运营上午 10 点把某商品从 100 元调成 80 元，
 * 而用户的购物车是昨天加的，存的还是 100。这个用户看到的是旧价格 ——
 * 他要么觉得「怎么结算时变便宜了」（还好），
 * 要么在反向调价时遇到「结算时怎么涨价了」（很糟，会被投诉）。
 *
 * <p>更危险的是下单：如果下单时用购物车里的价格算金额，
 * 那就等于<b>用户可以自己决定付多少钱</b>（改一下 Redis 或前端参数就行）。
 * 所以下单时的价格必须重新从数据库查。
 *
 * <p><b>可以推广的规则：</b>
 * <pre>
 *   缓存里只存「以缓存为准」的数据
 *   凡是「必须以数据库为准」的（价格、库存、状态），都别往缓存里放快照
 * </pre>
 * 缓存的作用是「省一次查询」，不是「造一份副本」。
 * 一旦副本和正本可能不一致，你就得为「什么时候该信谁」写一堆逻辑，
 * 而那些逻辑几乎必然有洞。
 *
 * <p>顺带一提，这和订单里必须存价格快照<b>正好相反</b>（里程碑 8 会讲）——
 * 订单为什么要存？因为订单是<b>历史事实</b>：
 * 「我当时是按 100 元买的」这件事永远不会变。
 * 而购物车是<b>当前意图</b>：「我现在想买这个」—— 当然要用现价。
 * <b>同一份数据（价格），在订单里要快照，在购物车里要实时，这不矛盾。</b>
 */
@Data
public class CartItemVO {

    /**
     * SKU id。★ 里程碑 15 阶段 4 起，<b>它是这一行的身份</b> ——
     * Redis 里存的 field 就是它，改数量、删除、下单勾选用的都是它。
     *
     * <p>它<b>一定有值</b>：即使对应的 SKU 已经在数据库里被删了，
     * 只要 Redis 里还有这条记录，这个字段就有值（它的来源就是 Redis）。
     * 所以排序、遍历、前端 :key 都可以放心用它，不用判空。
     */
    private Long skuId;

    /**
     * 商品 id。★ <b>它【可能是 null】，别拿它当主键用。</b>
     *
     * <p>它是从 SKU 查出来的（{@code product_sku.product_id} 再查商品），
     * 而那条查询带 {@code status = 1} —— 商品下架或被删时查不到，
     * 这一行就是 null。
     *
     * <p>留着它的唯一理由是「去商品详情页看看」这个链接
     * （{@code /product/{productId}}）。失效行给不出链接是<b>应该的</b> ——
     * 那件商品已经打不开了。
     */
    private Long productId;

    /**
     * 规格文本，形如 {@code "颜色:黑 / 尺码:M"}；无规格的商品是空串。
     *
     * <p>★ 里程碑 15 阶段 4 加的：同一件商品在购物车里可能占两行，
     * 不显示规格的话这两行看起来一模一样，用户根本不知道自己在删哪一行。
     *
     * <p>⚠️ <b>失效行为 null</b>（不是空串），而且这是<b>刻意的取舍</b>：
     * 规格文本要靠「SKU 行 + 商品」两样东西拼出来，
     * 而商品那条查询带 {@code status = 1} —— 失效行的商品本来就查不到。
     *
     * <p>为什么不为了失效行另开一条「不过滤 status」的查询？
     * 因为那等于给「用户端能看见什么」这条<b>安全规则开第二个口子</b>
     * （完整理由见 {@code ProductSkuMapper.selectByIds} 的注释），
     * 而它换来的只是「在一条用户无法操作、也点不开的灰色行上，
     * 多显示一句规格」。<b>代价是一个安全问题，收益是一点文案。</b>
     *
     * <p>★ 也正因为 null 和空串是两种含义，前端不能用 {@code v-if} 一刀切：
     * 能买的行要显示规格（可能为空串 = 真的没规格），
     * 失效的行显示不出来（null）。见 {@code Cart.vue} 的写法。
     */
    private String specText;

    /**
     * 商品名。
     *
     * <p>商品已下架或已删除时为 null，前端应该显示成「商品已失效」之类。
     * 这里的 null <b>是有意义的信息</b>，不是「还没查到」。
     */
    private String name;

    /** 单价。失效商品为 null —— 注意是 null 不是 0，别把「不知道价格」显示成「免费」 */
    private BigDecimal price;

    private String cover;

    /** 分类名，纯粹为了展示好看 */
    private String categoryName;

    /** 当前库存。<b>只用于展示和前端提示</b>，不作为能否下单的依据 */
    private Integer stock;

    /** 购物车里的数量。这个值一定 > 0 —— 数量减到 0 就应该删除记录而不是留着 0 */
    private Integer quantity;

    /** 小计 = price × quantity。失效商品为 null，前端不要显示成 ¥0.00 */
    private BigDecimal subtotal;

    /**
     * 这条商品现在还能不能买。
     *
     * <p>为 false 的两种情况：商品已下架/已删除，或者库存不足。
     *
     * <p><b>★ 为什么要有这个字段，而不是让前端自己看 price 是不是 null？</b>
     * 因为「能不能买」这个判断将来会变复杂：可能要加「限购」
     * 「活动未开始」「仅限会员」…… 让前端去猜这个规则，
     * 每次规则变化都要改前端。后端算好了直接给一个布尔值，
     * 前端只负责根据它切换显示样式。
     *
     * <p><b>判断逻辑放在哪一边，取决于「它是不是业务规则」。</b>
     * 是业务规则就放后端 —— 因为前端的任何判断都可以被绕过，
     * 而且两边各写一份迟早会不一致。
     */
    private Boolean available;

    /**
     * 不能买的原因，给用户看的一句话。
     *
     * <p>能买时为 null。这是「available 为 false 时才有的补充信息」——
     * 只告诉用户「不能买」而不告诉他为什么，是很糟糕的体验。
     */
    private String unavailableReason;
}
