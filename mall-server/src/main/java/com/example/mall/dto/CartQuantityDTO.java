package com.example.mall.dto;

import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotNull;
import lombok.Data;

/**
 * 「修改购物车里某个商品的数量」的请求体。
 *
 * <p>{@code PUT /api/shop/cart/items/204}
 * <pre>{ "quantity": 3 }</pre>
 *
 * <p>⚠️ 路径上那个数字是 <b>skuId</b>（里程碑 15 阶段 4 起），不是 productId。
 * 同一个商品的「黑色 S」和「白色 M」是两条独立的购物车记录，
 * 改数量只改其中一个。
 *
 * <h3>★ 为什么「加入购物车」和「修改数量」要分成两个接口？</h3>
 *
 * <p>看起来它们都是「设置数量」，合并成一个接口不是更省事吗？
 * 不行，因为两者的<b>语义完全不同</b>：
 *
 * <pre>
 *   加入购物车（POST）：quantity 是【增量】
 *     车里已有 2 件，POST quantity=3 → 变成 5 件
 *     这是用户的心智模型：「再加 3 件」
 *
 *   修改数量（PUT）：quantity 是【目标值】
 *     车里已有 2 件，PUT quantity=3 → 变成 3 件
 *     这是用户的心智模型：「改成 3 件」
 * </pre>
 *
 * <p>如果强行合并成一个接口，就必须多一个参数说明
 * 「这次的 quantity 是增量还是目标值」—— 那才是真的乱。
 * 而且这个参数一旦传错，用户会得到完全错误的结果
 * （想改成 3 件，结果变成了 5 件），还很难发现。
 *
 * <p><b>这正是 HTTP 方法语义的用处：</b>
 * <pre>
 *   POST   「做一件事」—— 通常是追加、创建，不幂等
 *          （点两次「加入购物车」就是加两次，符合预期）
 *   PUT    「把它变成某个状态」—— 幂等
 *          （发两次「改成 3 件」，结果都是 3 件）
 * </pre>
 * 用对方法，接口的含义就不用写文档解释了。
 *
 * <p>⚠️ 这里的 {@code @Min} 是 <b>1</b> 不是 0。
 * 「把数量改成 0」在语义上是「删除这件商品」，
 * 那应该调 DELETE 接口。允许 PUT 数量为 0 的话，
 * 后台就会留下 quantity=0 的记录 —— 它既不是「有」也不是「没有」，
 * 之后每个读购物车的地方都得过滤掉它。这种「幽灵数据」是 bug 的温床。
 * 用户在界面上把数量减到 0，前端应该调 DELETE。
 */
@Data
public class CartQuantityDTO {

    /**
     * 期望的最终数量。
     *
     * <h3>★ 为什么这里的 {@code @Max} 是 999，而不是 99？</h3>
     *
     * <p>因为「一个规格最多买 99 件」是<b>业务规则</b>，
     * 业务规则只能有一个地方说了算 —— 也就是
     * {@code BusinessRules.MAX_QUANTITY_PER_ITEM}。
     * （★ 里程碑 15 阶段 4：这个常量原来在 {@code CartServiceImpl} 里
     * 另有一份私有副本，两处都写着 99。收上去之后，这里引用的那句话才成立。）
     *
     * <p>一开始这里写的是 {@code @Max(99)}，看起来和 Service 一致，
     * 实际却造成了两个问题：
     * <pre>
     *   1. 同一个「数量超限」，走不同路径返回不同的业务码：
     *        单次请求 quantity=100    → DTO 先拦下 → 400
     *        车里已有 95 再加 10      → Service 判 → 1008
     *        车里已有 5，库存只剩 3    → Service 判 → 1008
     *      前端的「把输入框重置成最大值」要对两个码都处理一遍。
     *      而 400 原本的含义是「请求格式不对」，用它表达
     *      「你买得太多了」并不贴切 —— 请求格式一点问题都没有。
     *
     *   2. Service 里判 99 上限的那一段变成了【死代码】：
     *      参数绑定阶段就被拒的请求，根本进不了 Controller 方法。
     *      死代码比没有代码更糟 —— 读代码的人会以为它在生效。
     * </pre>
     *
     * <p>所以现在的分工是：
     * <pre>
     *   DTO 的 @Min(1) / @Max(999)  →  协议层的合理性检查
     *      0、负数、999999999 这类值，是【请求本身就不对】
     *      数量减到 0 应该调 DELETE，那是用错了接口
     *
     *   Service 里的 min(99, 库存)  →  真正的业务规则
     *      前端输入框的 max 就是 99，用户碰不到上面那条线，
     *      所以实际能被触发的「超限」只有 1008 这一种
     * </pre>
     *
     * <p><b>判断一个校验该放 DTO 还是 Service，就问一句：
     * 这个限制会不会变？由谁说了算？</b>
     * 会变、由业务说了算的（比如「最多买几件」）放 Service；
     * 不会变、属于协议常识的（比如「数量不能是负数」）放 DTO。
     * <b>同一个规则不要在两处都写，否则迟早会不一致。</b>
     */
    @NotNull(message = "数量不能为空")
    @Min(value = 1, message = "数量至少为 1，减到 0 请使用删除")
    @Max(value = 999, message = "数量超出合理范围")
    private Integer quantity;
}
