package com.example.mall.service;

import com.example.mall.dto.CartAddDTO;
import com.example.mall.dto.CartQuantityDTO;
import com.example.mall.vo.CartVO;

import java.util.List;
import java.util.Map;

/**
 * 购物车业务接口。
 *
 * <h3>存储选型：Redis 而不是 MySQL</h3>
 *
 * <p>购物车是本项目里<b>唯一</b>不落 MySQL 的业务数据。理由有三条，
 * 按重要性排序：
 *
 * <ol>
 *   <li><b>购物车是「临时意图」，不是「业务事实」。</b>
 *       用户加了又删、删了又加，改十次也没人关心中间过程。
 *       而订单一旦生成就永远不能变（那是要开发票、要对账的）。
 *       <b>会变且不重要 → 缓存；不会变且重要 → 数据库。</b></li>
 *
 *   <li><b>读写频率极高，且只按用户隔离。</b>
 *       用户逛商品时每点一次「加入购物车」就是一次写，
 *       而加购的转化率通常只有个位数百分比 ——
 *       绝大多数加购记录<b>永远不会变成订单</b>。
 *       把这些「噪音数据」写进 MySQL，商品表的磁盘和索引都会被拖累。</li>
 *
 *   <li><b>数据是天然的键值结构。</b>
 *       一个用户一个购物车，里面是「skuId → 数量」。
 *       这不用 Redis 的 Hash 用什么？
 *       ★ 注意是 skuId 不是 productId（里程碑 15 阶段 4 换的）——
 *         同一件商品的「黑色 S」和「白色 M」必须是两个 field，
 *         否则它们会被合并成一行、下单时也说不清买的是哪个规格。</li>
 * </ol>
 *
 * <p><b>★ 但 Redis 有个必须接受的代价：它可能丢数据。</b>
 * 默认的 Redis 持久化（RDB 快照）是「每隔一段时间存一次盘」，
 * 掉电可能丢掉最后几秒的写入。这个代价在购物车场景<b>完全可以接受</b> ——
 * 丢了几件加购记录，用户重新加一次就好了，没人会因此损失钱。
 *
 * <p>如果换成订单，「丢几秒数据」就等于「有用户的付款记录凭空消失」，
 * 那是事故。所以<b>「能不能用 Redis」从来不是看技术，是看数据丢了会怎样。</b>
 */
public interface CartService {

    /**
     * 把商品加入购物车。
     *
     * <p>{@code quantity} 是<b>增量</b>：车里已有 2 件时加 3 件，结果是 5 件。
     *
     * <p>会做这几项检查（任何一项不过就抛业务异常）：
     * <ul>
     *   <li>规格存在，且它所属的商品已上架</li>
     *   <li>累加后的数量不超过 {@code BusinessRules.MAX_QUANTITY_PER_ITEM}</li>
     *   <li>累加后的数量不超过<b>这个规格</b>的库存</li>
     * </ul>
     * ★ 里程碑 15 阶段 4：上面三项里的「商品」全部换成了「规格」。
     * 这正是 SKU 化的意义 —— 库存和价格挂在规格上，检查自然也要挂在那儿。
     *
     * <p><b>⚠️ 这里的库存检查是「尽力而为」，不是保证。</b>
     * 查库存和写 Redis 之间没有任何锁，理论上这中间库存可能被别人买走。
     * 但这<b>不是 bug，是刻意的设计</b>：
     * <ul>
     *   <li>加购时用户还没付钱，为他锁库存是不可接受的
     *       （一个恶意用户可以把所有商品的库存都锁死）</li>
     *   <li>真正必须严守库存的地方是<b>下单</b>（里程碑 8），
     *       那里会用数据库行锁 + {@code WHERE stock >= ?} 来保证</li>
     *   <li>这里检查只是<b>为了提前告诉用户「你买不了这么多」</b>，
     *       提升体验。它挡不住并发，也没打算挡住</li>
     * </ul>
     * 能清楚说出「哪一层负责防什么」比多加几把锁重要得多。
     */
    void add(CartAddDTO dto);

    /**
     * 把购物车里某个<b>规格</b>的数量<b>改成一个确定的值</b>。
     *
     * <p>和 {@link #add} 的区别见 {@code CartQuantityDTO} 的注释：
     * 这里是「改成 N 件」，不是「再加 N 件」。
     *
     * <p>如果车里根本没有这个规格，<b>会抛异常而不是静默创建</b> ——
     * 用 PUT 去做「新增」是接口语义混乱的开始。
     *
     * @param skuId 购物车里的 field。★ 里程碑 15 阶段 4 起是 SKU 不是商品 ——
     *              改「黑色 S」的数量不该动到「白色 M」
     */
    void updateQuantity(Long skuId, CartQuantityDTO dto);

    /**
     * 从购物车移除某个<b>规格</b>。
     *
     * <p><b>移除一个本来就不在车里的规格不算错误</b>（不抛异常）。
     * 这是刻意选择的「幂等」语义：用户连点两次删除按钮、
     * 或者在两个标签页里都点了删除，第二次应该安静地成功，
     * 而不是弹一个「该商品不在购物车中」的红色提示 ——
     * 用户的目的已经达到了（东西不在车里），为什么要报错？
     *
     * <p><b>「目标状态已经达成」就不该报错</b>，这是设计幂等接口的通用原则。
     */
    void remove(Long skuId);

    /** 清空购物车 */
    void clear();

    /**
     * 查询当前会员的完整购物车。
     *
     * <p>返回的条目<b>包含失效商品</b>（已下架/已删除的），
     * 它们会被标记 {@code available = false}，但不计入合计金额。
     * 为什么不是直接过滤掉？见 {@code CartItemVO.available} 的注释 ——
     * 静默消失的商品会让用户以为「我明明加过」。
     *
     * <p>⚠️ 失效条目上<b>只有 {@code skuId} 和 {@code quantity} 两个字段有值</b>
     * （商品名、价格、规格文本全是 null）—— 因为它们来自 Redis，
     * 而「商品信息和规格文本」要靠商品查询才拿得到，
     * 那条查询又把下架商品排除在外了。理由见 {@code CartItemVO.specText}。
     */
    CartVO getCart();

    /**
     * 查购物车里的商品<b>总件数</b>（不是条目数）。
     *
     * <p>给顶部导航栏的角标用。做成单独的方法而不是让前端
     * 调 {@link #getCart()} 再自己数，是因为角标在每个页面都要显示，
     * 而在每个页面都拉一次完整购物车（含所有商品的名称、价格、库存）
     * 是很浪费的 —— 角标只需要一个数字。
     *
     * <p><b>这是「接口粒度」的一个典型判断：</b>
     * 调用方需要的信息量小，就应该给它一个专门的小接口，
     * 而不是让它调大接口再挑出自己要的那一点点。
     */
    int count();

    // ==========================================================================
    // 以下两个方法是给【下单】（里程碑 8）用的。
    //
    // ★ 为什么订单模块要通过这两个方法读购物车，
    //   而不是自己注入 StringRedisTemplate 去 HGETALL？
    //
    //   因为「购物车的 Redis key 怎么拼」这件事，只应该有一个地方知道。
    //   如果 OrderServiceImpl 里也写一遍 "mall:cart:" + memberId，
    //   那么这行字符串就有了两个出处：
    //     改前缀时漏改一个，订单就会读到"另一个购物车"——
    //     而现象是"下单时购物车是空的"，完全看不出是 key 拼错了。
    //     （这正是 CartServiceImpl 里那句"拼 key 的规则只有一处"的意思，
    //       只是现在这个"一处"要跨模块守住。）
    //
    //   同理，将来购物车从 Redis 换成 MySQL、或者 key 结构变了，
    //   改购物车模块内部就行，订单模块一行都不用动。
    //
    //   **一个模块的数据结构，只能由它自己解释。**
    //   别人想用，就得通过它给出的方法。
    // ==========================================================================

    /**
     * 读取购物车里指定商品的<b>数量</b>，供下单时确定「每种买几件」。
     *
     * <p>返回的是传入 id 里<b>确实在购物车中</b>的那些，
     * 不在车里的 id 不会出现在返回结果中。
     *
     * <p>⚠️ 刻意<b>不</b>在「有 id 不在车里」时抛异常 ——
     * 这里只负责<b>报告事实</b>（车里有什么、各多少），
     * 「缺失的商品该怎么办」是<b>下单的策略</b>，由 {@code OrderService} 决定。
     *
     * <p><b>★ 为什么要分得这么清？</b>因为同一份事实，
     * 不同的场景可能要不同的处理：
     * <pre>
     *   下单结算 → 缺了就得报错（用户勾的东西买不了了）
     *   将来做"再来一单" → 缺了可以静默跳过（老订单里有商品下架了）
     * </pre>
     * 如果这里直接抛异常，第二种场景就没法复用了。
     * <b>「判断事实」和「决定怎么办」分开，方法才能被多处复用。</b>
     *
     * @param skuIds 要查的 SKU id。<b>调用方保证非空</b>
     * @return skuId → 数量。只包含在车里的那些，可能为空 Map（不会是 null）
     */
    Map<Long, Integer> readQuantities(List<Long> skuIds);

    /**
     * 从购物车里移除指定的<b>规格</b>，供下单成功后清理用。
     *
     * <p>和 {@link #remove} 是同一个语义，只是支持一次删多个 ——
     * 结算 5 种规格后要删 5 个字段，逐个调 {@code HDEL} 就是 5 次网络往返。
     *
     * <p>⚠️ <b>调用时机的纪律：必须在订单事务提交之后调用。</b>
     * 理由见 {@code OrderServiceImpl} —— 如果提交前就把购物车清了，
     * 而事务后来回滚了，用户的购物车就凭空空了，订单却没生成。
     *
     * <p>幂等：删一个已经不在车里的规格不报错（和 {@link #remove} 一致）。
     *
     * <p>★★ <b>里程碑 15 阶段 4 最容易静默出错的调用点，就是这里。</b>
     * 它原来的参数是 productIds，而车里现在的 field 是 skuId ——
     * 传错的下场不只是「什么都没删掉」，而是
     * <b>productId 撞上别人的 skuId，把用户车里另一行删掉</b>。
     * 更糟的是它是在订单事务提交后的回调里被调的，
     * 那里抛的异常只打一条日志（见 {@code OrderServiceImpl}），
     * 所以<b>没有任何一层会报错</b>。
     *
     * @param skuIds 要移除的 SKU id。空集合时直接返回（不报错）
     */
    void removeItems(List<Long> skuIds);
}
