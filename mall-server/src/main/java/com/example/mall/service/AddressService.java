package com.example.mall.service;

import com.example.mall.dto.AddressSaveDTO;
import com.example.mall.entity.MemberAddress;

import java.util.List;

/**
 * 收货地址簿业务接口。
 *
 * <h3>★ 这个模块的核心是维护一条「不变量」</h3>
 *
 * <p>不说出来的话，地址簿看起来就是一堆增删改查。但它真正要做的是
 * 保证下面这条规则<b>在任何时候都成立</b>：
 *
 * <pre>
 *   一个会员的地址里，【最多】有一个是默认地址；
 *   只要他有地址，就【恰好】有一个是默认地址。
 * </pre>
 *
 * <p>这条规则为什么重要？因为下单页打开时要「默认选中一个地址」。
 * 如果没有默认地址，用户每次下单都得手动选一次；
 * 如果有两个默认地址，那就是「到底选哪个」的不确定性 ——
 * 而<b>下单这种动作不能有不确定性</b>。
 *
 * <p><b>★ 而这条不变量是数据库表达不了的</b>，这是本节最关键的一点：
 * <ul>
 *   <li>「最多一个」可以用唯一索引表达，但只能写成
 *       {@code UNIQUE KEY (member_id, is_default)} —— 而这样
 *       一个会员就<b>只能存一个地址</b>了，因为非默认的全是 0，撞车</li>
 *   <li>（MySQL 也没有「部分索引」这种东西，PostgreSQL 有：
 *       {@code CREATE UNIQUE INDEX ... WHERE is_default = 1}）</li>
 *   <li>「恰好一个」更没法用约束表达 —— 约束管的是「行内/行间的值」，
 *       管不了「这几行里必须有一行满足某条件」</li>
 * </ul>
 *
 * <p>所以这条不变量只能由 Service 在<b>每一个会破坏它的操作</b>里维护：
 * 新增、修改、设为默认、删除。漏掉任何一个，数据就会慢慢变脏。
 *
 * <p><b>判断一个约束该放数据库还是应用层的标准是：
 * 数据库能不能完整地表达它。</b>能表达就放数据库（比如重名用唯一索引），
 * 表达不全的就别硬塞，老老实实在 Service 里维护 ——
 * 但这时候要清楚：<b>你是在用代码手工维护一条数据库不会帮你守的规则，
 * 所以每个入口都得想到它。</b>
 */
public interface AddressService {

    /**
     * 查当前会员的全部地址。
     *
     * <p>默认地址排在最前。这个顺序由 SQL 保证，不靠前端再排一遍。
     */
    List<MemberAddress> list();

    /**
     * 查当前会员的默认地址。
     *
     * <p>下单页打开时用它来预选。
     *
     * @return 没有默认地址时返回 {@code null}。
     *         <b>这不是错误</b> —— 一个刚注册、还没存过地址的用户
     *         就是这个状态。把它当成错误会让新用户在下单页看到
     *         一个红色的报错，而他什么也没做错。
     */
    MemberAddress getDefault();

    /**
     * 新增地址。
     *
     * <p>两种情况会自动把它设为默认（并清掉原来的默认）：
     * <ul>
     *   <li>这是该会员的<b>第一个</b>地址 —— 不设为默认的话，
     *       用户存完地址去下单，会发现一个都没选中，还得手动去设一次</li>
     *   <li>请求里明确传了 {@code isDefault = true}</li>
     * </ul>
     *
     * @return 新增地址的 id
     */
    Long create(AddressSaveDTO dto);

    /**
     * 修改地址。
     *
     * <p>⚠️ 只能改<b>自己的</b>地址 —— id 是别人的会被当成「地址不存在」。
     * 见 {@link com.example.mall.mapper.MemberAddressMapper} 的类注释。
     *
     * <h4>★ 这是【全量替换】，不是局部更新</h4>
     *
     * <p>{@code receiver / phone / region / detail} 四个字段<b>必须全传</b>，
     * 少传任何一个都会得到 400。这是 {@code PUT} 这个词本身的意思 ——
     * 「用我给的这份数据替换掉那条记录」。
     *
     * <p>为什么不做局部更新？因为<b>没有这个需求</b>：会调这个接口的
     * 只有地址表单页，而表单页手上有全部字段（用户就是在那个表单里改的）。
     * 唯一一个「手上有 id 但没有完整数据」的场景是列表页的「设为默认」，
     * 它走的是下面的 {@code setDefault}。
     *
     * <p><b>★ 换句话说：{@code setDefault} 这个独立接口的存在，
     * 就是为了让 {@code update} 不必变成局部更新。</b>
     * 两个接口各自服务一种「手头已有的数据」，
     * 就不需要一个能接受半份数据的接口了。
     *
     * <p>{@code dto.isDefault} 是唯一的例外，它<b>可以不传</b>：
     * {@code null} 表示不动默认状态，{@code true} 表示设为默认，
     * {@code false} 表示取消默认。它和其它四个字段的性质不同 ——
     * 那四个是"这条记录的内容"，它是"一个开关"。
     * 开关没有「必须表态」的道理，不表态就当没碰它。
     */
    void update(Long id, AddressSaveDTO dto);

    /**
     * 把指定地址设为默认。
     *
     * <p>和 {@code update(id, dto)} 传 {@code isDefault = true} 效果一样。
     * 这个接口存在的意义是<b>让前端少传数据</b>：
     * 地址列表页上的「设为默认」按钮不需要把收货人、电话、地址全文
     * 再传一遍 —— 那些字段没变，传了只是多一份出错的机会
     * （比如列表页拿到的数据是几分钟前的，重传反而会把新改的内容覆盖回旧的）。
     *
     * <p><b>★ 这是「为同一个意图提供两个接口」的正当理由：
     * 不是功能重复，而是「手头已有的数据」不同。</b>
     * 表单页手上有完整数据，用它去 update；
     * 列表页手上有 id，用它去 setDefault。
     */
    void setDefault(Long id);

    /**
     * 删除地址。
     *
     * <p>如果删掉的正好是默认地址，并且该会员还有别的地址，
     * 会自动把最新的一条提为默认 —— 见实现里的说明。
     */
    void delete(Long id);
}
