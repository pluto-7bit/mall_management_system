package com.example.mall.util;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.concurrent.ThreadLocalRandom;

/**
 * 订单号生成器。
 *
 * <h3>订单号为什么不能直接用自增主键？</h3>
 *
 * <p>表里已经有 {@code id} 了，看起来订单号是多余的。但有四个理由让它必须存在：
 *
 * <ol>
 *   <li><b>不能把业务量暴露给外界。</b>
 *       {@code id = 10023} 明明白白告诉所有人「这个平台一共才一万单」。
 *       竞品不用做调研，下几单就知道了。订单号必须是<b>看不出规律</b>的。</li>
 *
 *   <li><b>不能让人猜到别人的单。</b>
 *       如果订单号是连号的，那么改一下 URL 里的数字就能翻到别人的订单。
 *       这不是小事 —— 那是别人的姓名、电话、住址。
 *       （当然，接口本身还得校验归属，见 {@code OrderMapper} 的注释。
 *         但「猜不到」是不该被放弃的第一道防线。）</li>
 *
 *   <li><b>它是给外部用的编号，得能独立演进。</b>
 *       自增 id 是数据库的内部标识，将来分库分表、
 *       数据迁移都可能会变；而订单号印在发票上、写在快递单上，
 *       一旦发出去了就永远不能变。</li>
 *
 *   <li><b>现实中它承载业务含义。</b>
 *       客服接到电话问「我的单到哪了」，用户报的就是订单号。</li>
 * </ol>
 *
 * <h3>本项目采用的格式</h3>
 *
 * <pre>
 *   20260922005831  +  482913
 *   └─ 14 位时间 ─┘    └ 6 位随机 ┘
 * </pre>
 *
 * <p><b>为什么是「时间 + 随机」而不是纯随机（比如 UUID）？</b>
 * 因为带时间前缀有两个实际好处：
 * <ul>
 *   <li>人眼能看出下单时间，客服排查问题时非常有用</li>
 *   <li>订单号<b>大致按时间递增</b>，做分页和归档时能利用这个顺序</li>
 * </ul>
 *
 * <p><b>★ 那 6 位随机够不够？会撞吗？</b>会，但概率极低，而且我们有兜底。
 * 算一下：同一秒内最多能有多少个订单？
 * <pre>
 *   6 位随机 = 100 万种可能
 *   一秒内下 100 单（对学习项目来说已经很夸张了）时，
 *   至少撞一次的概率约 1 - (1 - 1/1000000)^(100*99/2) ≈ 0.5%
 * </pre>
 * 换句话说，<b>一秒内一百个订单，大约两百次里才会撞一次</b>。
 * 而真撞上的时候，数据库的 {@code uk_order_no} 唯一索引会直接拒绝插入，
 * 不会产生两个一样的订单号。
 *
 * <h3>★ 关键：能撞，但撞了之后怎么办</h3>
 *
 * <p>唯一索引只是「最后一道防线」，它负责<b>不让错误的数据进库</b>，
 * 但它不负责<b>让这次下单成功</b>。所以 {@code OrderServiceImpl} 里
 * 捕获了唯一键冲突，然后<b>换一个订单号重试一次</b>。
 *
 * <p><b>「加唯一索引」和「处理唯一索引冲突」是两件事，缺一不可。</b>
 * 只加索引不处理，用户会看到一个莫名其妙的系统错误；
 * 只处理不加索引，那就是靠概率防重，迟早出事。
 *
 * <p>⚠️ 真实项目里更常用的是<b>号段模式</b>（数据库里存一个
 * 「当前最大号」，服务一次领 1000 个号在内存里发）或者<b>雪花算法</b>。
 * 它们能在完全避免碰撞的同时保持有序。本项目不用，
 * 是因为那属于分布式 ID 的范畴，和「把分层讲清楚」这个目标关系不大 ——
 * 但要知道这条路存在，也要知道这里的选择是有意识的简化。
 */
public final class OrderNoGenerator {

    private OrderNoGenerator() {
    }

    /** 时间部分的格式：年月日时分秒，共 14 位 */
    private static final DateTimeFormatter TIME_FORMAT =
            DateTimeFormatter.ofPattern("yyyyMMddHHmmss");

    /** 随机部分的位数 */
    private static final int RANDOM_BOUND = 1_000_000;

    /**
     * 生成一个订单号。格式：14 位时间 + 6 位随机，共 20 位。
     *
     * <p>20 位没有超出 {@code orders.order_no} 的 {@code VARCHAR(32)}。
     * <b>生成规则的位数必须小于等于数据库列的宽度</b> ——
     * 这个约束看起来显然，但改格式的时候（比如把随机部分从 6 位加到 10 位）
     * 很容易忘记回来看一眼列宽。写在这里，就是为了改格式时有个提醒。
     */
    public static String generate() {
        return LocalDateTime.now().format(TIME_FORMAT)
                + String.format("%06d", ThreadLocalRandom.current().nextInt(RANDOM_BOUND));
    }
}
