package com.example.mall.common;

/**
 * 跨模块共用的业务规则常量。
 *
 * <h3>★ 为什么要有这么一个类？</h3>
 *
 * <p>因为有些业务数字<b>天然属于多个模块</b>，而它们必须只有一个定义。
 *
 * <p>这里的 {@link #MAX_QUANTITY_PER_ITEM} 就是典型：
 * <ul>
 *   <li>{@code CartService} 要用它 —— 加购和改数量时判断上限</li>
 *   <li>{@code OrderService} 要用它 —— 「立即购买」绕过购物车直接下单，
 *       也得受同一个上限约束</li>
 * </ul>
 *
 * <h3>★ 这个类的存在，本身是里程碑 7 那次踩坑的结果</h3>
 *
 * <p>最初这个数字有<b>三个</b>出处：{@code CartAddDTO} 上一个
 * {@code @Max(99)}、{@code CartQuantityDTO} 上一个 {@code @Max(99)}、
 * {@code CartServiceImpl} 里一个私有常量。当时以为这是「双重保险」，
 * 实际结果是：DTO 上那两个在<b>参数绑定阶段</b>就把请求拒掉了，
 * Service 里判 99 上限的代码<b>永远执行不到</b>，成了死代码；
 * 而且同一个用户动作会得到两个不同的错误码（400 和 1008）。
 *
 * <p>修的时候做的决定是：<b>DTO 只做协议层的合理性检查（不为空、是正数、
 * 不是 999999999 这种明显乱填的），业务上限一律由 Service 判断。</b>
 * 于是这个数字在 Service 层只剩一处 —— 而现在订单模块也要用它，
 * 如果让它继续当 {@code CartServiceImpl} 的私有常量，
 * 订单模块要么去引用购物车的内部实现（方向反了），
 * 要么自己再写一个 99（那就是把踩过的坑重新挖一遍）。
 *
 * <p>所以把它提到这里：<b>它的归属不是「购物车的规则」也不是「订单的规则」，
 * 而是「这个商城对单个商品一次能买多少的规定」。</b>
 *
 * <h3>⚠️ 不要把什么都往这里塞</h3>
 *
 * <p>只有<b>真的被两个以上模块用到</b>的规则才放进来。
 * 一个只在 {@code AddressServiceImpl} 里用的数字应该留在那儿 ——
 * 「共用的常量类」很容易变成「什么都不知道该放哪的东西都往里扔」的垃圾桶，
 * 那时候它就丧失了存在的意义：<b>它本该回答「这条规则属于谁」，
 * 一旦什么都有，它就什么也没说明。</b>
 */
public final class BusinessRules {

    /** 工具类不应该被实例化 */
    private BusinessRules() {
    }

    /**
     * 单个商品一次最多能买多少件。
     *
     * <p>购物车加购、购物车改数量、立即购买、下单 —— 这四个入口
     * 都用这一个数字。改的话只改这一行。
     *
     * <p><b>为什么要有这个上限？</b>不是为了防库存，而是防「手滑和恶意」：
     * <pre>
     *   手滑   → 数量输入框里多按一个 0，从 2 件变成 20 件
     *   恶意   → 有人写个脚本一次下单 999999 件，把库存和订单表都撑爆
     * </pre>
     * 真实商城还会有「每个订单最多多少种商品」「单个订单金额上限」之类的规则，
     * 本项目只留这一条，够把「规则该放在哪一层」讲清楚就行。
     */
    public static final int MAX_QUANTITY_PER_ITEM = 99;
}
