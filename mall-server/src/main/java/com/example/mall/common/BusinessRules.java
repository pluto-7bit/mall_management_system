package com.example.mall.common;

/**
 * 跨模块共用的业务规则常量。
 *
 * <h3>★ 为什么要有这么一个类？</h3>
 *
 * <p>因为有些业务数字<b>天然属于多个模块</b>，而它们必须只有一个定义。
 *
 * <p>这里的 {@link #MAX_QUANTITY_PER_ITEM} 就是典型：
 * <ul>
 *   <li>{@code CartService} 要用它 —— 加购和改数量时判断上限</li>
 *   <li>{@code OrderService} 要用它 —— 「立即购买」绕过购物车直接下单，
 *       也得受同一个上限约束</li>
 * </ul>
 *
 * <h3>★ 这个类的存在，本身是里程碑 7 那次踩坑的结果</h3>
 *
 * <p>最初这个数字有<b>三个</b>出处：{@code CartAddDTO} 上一个
 * {@code @Max(99)}、{@code CartQuantityDTO} 上一个 {@code @Max(99)}、
 * {@code CartServiceImpl} 里一个私有常量。当时以为这是「双重保险」，
 * 实际结果是：DTO 上那两个在<b>参数绑定阶段</b>就把请求拒掉了，
 * Service 里判 99 上限的代码<b>永远执行不到</b>，成了死代码；
 * 而且同一个用户动作会得到两个不同的错误码（400 和 1008）。
 *
 * <p>修的时候做的决定是：<b>DTO 只做协议层的合理性检查（不为空、是正数、
 * 不是 999999999 这种明显乱填的），业务上限一律由 Service 判断。</b>
 * 于是这个数字在 Service 层只剩一处 —— 而现在订单模块也要用它，
 * 如果让它继续当 {@code CartServiceImpl} 的私有常量，
 * 订单模块要么去引用购物车的内部实现（方向反了），
 * 要么自己再写一个 99（那就是把踩过的坑重新挖一遍）。
 *
 * <h3>⚠️ 里程碑 15 阶段 4：上面那句「Service 层只剩一处」<b>当时其实不成立</b></h3>
 *
 * <p>提上来的时候，{@code CartServiceImpl} 里那个私有常量<b>并没有被删掉</b> ——
 * 它还在那里，还是 99。也就是说从里程碑 7 到 15 之间，
 * 「最多买几件」在 Service 层一直是<b>两份</b>：
 * <pre>
 *   BusinessRules.MAX_QUANTITY_PER_ITEM          ← 订单侧在用
 *   CartServiceImpl.MAX_QUANTITY_PER_ITEM        ← 购物车侧在用（私有副本）
 * </pre>
 * 两个值恰好相等，所以<b>没有任何测试能发现它</b>，而这一段的注释
 * 一直写着「只剩一处」。<b>「两处值相等」比「两处值不等」危险得多</b> ——
 * 不等的话早就有人撞上去了，相等的话它可以一直错下去。
 *
 * <p>阶段 4 顺手把那份私有副本收掉了（购物车改用这里这一个）。
 * <b>★ 记住这个形态：注释说的和代码做的不一致，是一个可以活很久的 bug</b> ——
 * 它不需要任何东西出错，只需要没人去核对那句话。
 *
 * <p>所以把它提到这里：<b>它的归属不是「购物车的规则」也不是「订单的规则」，
 * 而是「这个商城对单个商品一次能买多少的规定」。</b>
 *
 * <h3>⚠️ 不要把什么都往这里塞</h3>
 *
 * <p>只有<b>真的被两个以上模块用到</b>的规则才放进来。
 * 一个只在 {@code AddressServiceImpl} 里用的数字应该留在那儿 ——
 * 「共用的常量类」很容易变成「什么都不知道该放哪的东西都往里扔」的垃圾桶，
 * 那时候它就丧失了存在的意义：<b>它本该回答「这条规则属于谁」，
 * 一旦什么都有，它就什么也没说明。</b>
 */
public final class BusinessRules {

    /** 工具类不应该被实例化 */
    private BusinessRules() {
    }

    /**
     * 单个商品一次最多能买多少件。★ 里程碑 15 阶段 4 起是「<b>单个规格</b>」的上限。
     *
     * <p>购物车加购、购物车改数量、立即购买、下单 —— 这四个入口
     * 都用这一个数字。改的话只改这一行。
     *
     * <p>⚠️ <b>「单个规格」这四个字是阶段 4 补的，而且它意味着一条做不到的事：</b>
     * 购物车的 Redis field 从 productId 换成 skuId 之后，
     * 「这件商品一共加了多少件」<b>不再 O(1) 可得</b> ——
     * 要算它就得把该商品的每一条规格都查出来再相加。
     * 所以 99 只能是「每个规格各自 99」，做不出「每件商品合计 99」。
     * <b>这是刻意的取舍</b>（见 README 的已知取舍），不是没想到。
     *
     * <p><b>为什么要有这个上限？</b>不是为了防库存，而是防「手滑和恶意」：
     * <pre>
     *   手滑   → 数量输入框里多按一个 0，从 2 件变成 20 件
     *   恶意   → 有人写个脚本一次下单 999999 件，把库存和订单表都撑爆
     * </pre>
     * 真实商城还会有「每个订单最多多少种商品」「单个订单金额上限」之类的规则，
     * 本项目只留这一条，够把「规则该放在哪一层」讲清楚就行。
     */
    public static final int MAX_QUANTITY_PER_ITEM = 99;

    // ======================================================================
    // ★ 里程碑 15：商品多规格（SKU）的几条上限
    // ======================================================================

    /**
     * 一件商品最多能有几个规格维度（「颜色」「内存」「尺码」= 3 维）。
     *
     * <p><b>为什么要有这个上限？</b>不是为了防库存，是防<b>组合爆炸</b>：
     * 规格是叉乘出来的，3 维各 10 个值就是 1000 行 SKU ——
     * 而运营填不完 1000 行价格，最后一定会得到一个填了一半、
     * 被 {@link #MAX_SKU_COUNT} 拒绝的请求，然后来问「为什么保存不了」。
     * 在维度这个入口就拦住，错误信息才说得清楚。
     *
     * <p>⚠️ 它和「每维最多几个值」是<b>两条独立</b>的限制，
     * 但 3 × 10 = 30 已经超过 {@link #MAX_SKU_COUNT}，
     * 所以真正起作用的那条永远是组合数 —— 这两条存在的意义是
     * <b>在用户还没填满整张表之前就告诉他方向错了</b>。
     */
    public static final int MAX_SKU_DIMENSIONS = 3;

    /**
     * 一个规格维度最多能有几个取值（「颜色」最多 10 种）。
     *
     * <p>它同时是 {@code product.spec_schema} 那一列能装下的前提，
     * 见 {@link #MAX_SPEC_SCHEMA_LENGTH}。
     */
    public static final int MAX_SPEC_VALUES_PER_DIM = 10;

    /**
     * 一件商品最多能有几行 SKU（各维取值数的乘积）。
     *
     * <p>它是「叉乘结果」的硬上限：{@code skus.length} 必须<b>恰好等于</b>
     * 各维取值数之积，少了是漏行（商家声明的某个规格没有价格），
     * 多了是这个上限。
     */
    public static final int MAX_SKU_COUNT = 60;

    /** 规格名（「颜色」「内存」）的最大长度。取值偏小是故意的：它要一起塞进下面那 500 字节 */
    public static final int MAX_SPEC_NAME_LENGTH = 10;

    /** 单个规格值（「黑」「128G」）的最大长度。同上 */
    public static final int MAX_SPEC_VALUE_LENGTH = 20;

    /**
     * {@code product.spec_schema} 那一列能装下的字符数 —— 就是建表时的
     * {@code VARCHAR(500)}，这里不是「再定一个上限」，是<b>把数据库的限制抄一份到 Java 里</b>。
     *
     * <p><b>为什么必须在 Java 侧再判一次？</b>
     * 因为在 Service 里判能得到一句「规格定义太长了，请精简」，
     * 而不判的话超长会一路走到 INSERT，然后是一条
     * {@code Data too long for column 'spec_schema'} 的 SQL 错 ——
     * 用户看到的是「服务器错误」，而且是<b>保存之后</b>才知道的。
     *
     * <p>⚠️ 光有 {@link #MAX_SKU_DIMENSIONS} 和 {@link #MAX_SPEC_VALUES_PER_DIM}
     * <b>挡不住</b>这个长度：3 维 × 10 个 20 字的取值，
     * 序列化出来约 780 字符，远超 500。所以这条检查是必需的，
     * 不能靠「维度少、值少，肯定放得下」的直觉。
     */
    public static final int MAX_SPEC_SCHEMA_LENGTH = 500;

    /**
     * 单个规格的库存上限。
     *
     * <p><b>为什么需要一个上限？</b>因为 {@code product.stock} 在阶段 2~5 期间
     * 是各 SKU 库存的<b>汇总</b>（{@code SUM(sku.stock)}），而那一列是 {@code INT}。
     * 不设上限的话，60 个规格各填一个接近 {@code Integer.MAX_VALUE} 的库存，
     * 求和就溢出了 —— 一个安静的、只在极端输入下出现的错值。
     *
     * <p>算术：{@link #MAX_SKU_COUNT} × 本条 = 60 × 999999 = 59,999,940，
     * 远小于 {@code Integer.MAX_VALUE}（2,147,483,647）。<b>有上限就恒不溢出</b>，
     * 所以不需要再写一个「求和后判 long」的运行时检查。
     *
     * <p>⚠️ 这个数字<b>不放在 DTO 上</b>：它是业务规则，不是协议层检查
     * （见类注释里里程碑 7 那段教训）。DTO 上只有 {@code @Min(0)}。
     */
    public static final int MAX_SKU_STOCK = 999999;
}
