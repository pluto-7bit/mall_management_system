package com.example.mall.common;

/**
 * 业务状态码常量。
 *
 * <p>用常量而不是到处写魔法数字 {@code 200}，好处是：
 * 以后要改规则（比如成功码改成 0）只改一个地方；
 * 写错 {@code 2000} 这种手误编译期也不会报错，但用常量写错名字编译直接失败。
 *
 * <p><b>为什么要有业务错误码，直接用 HTTP 状态码不行吗？</b>
 *
 * <p>HTTP 状态码表达的是「<b>这次请求本身</b>怎么样了」：
 * <pre>
 *   200 请求成功  400 请求格式错  401 没登录  403 没权限  500 服务器炸了
 * </pre>
 * 而业务错误表达的是「<b>请求没错，但你要求的这件事做不成</b>」：
 * <pre>
 *   库存不足、订单状态不允许取消、分类下有商品不能删、余额不够
 * </pre>
 * 这些都是「请求完全合法」的情况，用 400 表达不准确，用 500 更是误导
 * （明明是正常的业务分支，却报「服务器错误」，监控上会一片红）。
 *
 * <p>所以标准做法是：<b>HTTP 状态码一律 200（表示请求处理完了），
 * 业务结果看响应体里的 code 字段</b>。
 * 本项目就是这么做的，前端拦截器里判断的正是这个 code。
 *
 * <p><b>码段划分</b>：
 * <ul>
 *   <li>200      成功</li>
 *   <li>400      参数校验失败</li>
 *   <li>401      未登录 / token 失效</li>
 *   <li>403      已登录但无权限</li>
 *   <li>500      系统内部错误</li>
 *   <li>1001~    业务错误（库存不足、订单状态不允许、售后超期等）</li>
 * </ul>
 *
 * <p><b>为什么业务错误码要从 1001 开始而不是 1、2、3？</b>
 * 当年写的是「留出位数，将来可以按模块分段：1xxx 商品/分类，
 * 2xxx 订单，3xxx 会员。现在还没这个必要」。
 *
 * <h3>★★ 里程碑 17：已经决定了 —— <b>不分段</b>，理由如下</h3>
 *
 * <p>那句「现在还没这个必要」是个坏注释：它不解释任何事，
 * 而且会一直邀请下一个人重新问一遍「现在呢？」——
 * 每一轮都要重新论证一次同一件事。所以这一轮把它结论化。
 * （{@code BusinessRules} 的类注释里记过一次同类的教训：
 * 「注释说的和代码做的不一致，是一个可以活很久的 bug」。）
 *
 * <p><b>决定不分段，三条理由：</b>
 * <ol>
 *   <li><b>已经发出去的码不能重排。</b>{@code 1002} 永远是 1002 ——
 *       它写在两端的前端代码里、写在 README 里、写在测试脚本的断言里。
 *       强行分段意味着给已有业务码搬家，
 *       而搬错了的症状是「前端判断了 1002、后端现在返回 2002」，
 *       静默地走错分支。</li>
 *   <li><b>半途分段比分段之前更难查。</b>分段唯一的收益是
 *       「看码就知道归属」，而它要求<b>整个区间重排</b>。
 *       如果只把新码放进 2xxx，那么订单相关的码会一半在 1xxx、一半在 2xxx ——
 *       下一个人查一个订单错误码要去哪一段找，答案是「都找一遍」。
 *       收益没了，成本照付。</li>
 *   <li><b>码的归属本来就不是它最有用的信息。</b>查一个码时真正想知道的是
 *       「谁在什么时候会返回它」—— 那靠的是这个文件里的注释和
 *       README 的接口说明，不是数字区间。</li>
 * </ol>
 *
 * <p>★ 所以我们继续往后追加（1012、1013、1014……），
 * 并且记一条 README 已知取舍：<b>如果重来一次，应该在建这个类的
 * 那一轮就把分段定死</b> —— 那时候重排的成本是零。
 */
public final class ResultCode {

    /** 工具类不应该被实例化 */
    private ResultCode() {
    }

    public static final int SUCCESS = 200;
    public static final int BAD_REQUEST = 400;
    public static final int UNAUTHORIZED = 401;
    public static final int FORBIDDEN = 403;
    public static final int ERROR = 500;

    // ---- 业务错误码 ----

    /** 库存不足 */
    public static final int STOCK_NOT_ENOUGH = 1001;

    /**
     * 状态不允许该操作。
     *
     * <p>★ 里程碑 17 起它<b>同时管订单状态和售后状态</b>（原文只写了「订单状态」）。
     * 这是刻意的复用，不是顺手：判据是<b>前端收到它要做的事情一样不一样</b> ——
     * 两种情况下前端要做的都是「弹一句提示 + 重查列表」，
     * 因为「到底是什么状态」这件事只有重查才知道（响应里不带）。
     *
     * <p>对比 {@link #CART_QUANTITY_LIMIT} 那种「前端要弹一个带按钮的框」
     * 的码 —— <b>那个码存在的理由是「前端要做不一样的事」</b>，
     * 而这里前端要做的事完全一样，多开一个码只会让「哪些码表示状态不对」
     * 这件事多一个需要记住的地方。
     *
     * <p>⚠️ 反过来，售后那两个新码（{@link #AFTER_SALE_EXISTS} /
     * {@link #ORDER_ITEM_REFUNDED}）<b>没有</b>复用 1002，
     * 正是因为前端对它们要做不一样的事（把那一行标成某个状态、去掉入口，
     * 而不是弹提示）。<b>分不分，看前端；不看后端觉得像不像。</b>
     */
    public static final int ORDER_STATUS_INVALID = 1002;

    /** 数据不存在 */
    public static final int NOT_FOUND = 1003;

    /**
     * 分类下还挂着商品，不允许删除。
     *
     * <p>这个码是给前端做<b>差别处理</b>用的：
     * 前端可以判断 {@code code === 1004} 时弹一个「去查看该分类的商品」的按钮，
     * 而其他错误就只弹一句提示。
     * 如果所有业务错误都用同一个码，前端就只剩「显示一句错误信息」这一个选择了。
     */
    public static final int CATEGORY_HAS_PRODUCT = 1004;

    /** 名称重复（分类名、商品名等） */
    public static final int DUPLICATE_NAME = 1005;

    /**
     * 账号或密码错误。
     *
     * <p>注意「账号不存在」和「密码错误」共用这一个码 ——
     * 这是刻意的，目的是防止攻击者通过错误码差异枚举出
     * 哪些账号真实存在（见 AuthServiceImpl.login 的注释）。
     *
     * <p>「账号被禁用」也复用它，因为告诉攻击者「这个账号存在但被禁用了」
     * 同样是信息泄漏。
     */
    public static final int LOGIN_FAILED = 1006;

    /**
     * 注册时账号已被占用。
     *
     * <p><b>为什么不复用 {@link #DUPLICATE_NAME}（1005）？</b>
     *
     * <p>因为这两件事前端要做的事情不一样：
     * <ul>
     *   <li>1005 用在管理端新增分类/商品时 —— 弹一句提示就够了，
     *       操作的人知道自己刚填了什么</li>
     *   <li>1007 用在用户注册时 —— 前端要把光标<b>聚焦回账号输入框</b>，
     *       提示「换一个试试」，而不是让用户自己去找是哪一项出了问题</li>
     * </ul>
     *
     * <p>这是一种常见的取舍：错误码分得越细，前端能做的差别处理就越多，
     * 但码表也越长。判断标准是<b>「前端需不需要针对它做不同的动作」</b>，
     * 而不是「这两个错误在语义上是不是同一类」。
     */
    public static final int USERNAME_TAKEN = 1007;

    /**
     * 购物车里单个商品的数量超出上限，或者超过库存。
     *
     * <p><b>为什么不用 {@link #STOCK_NOT_ENOUGH}（1001）？</b>
     *
     * <p>虽然「加购数量超过库存」看起来就是库存不足，但前端要做的事不一样：
     * <ul>
     *   <li>1001 库存不足 —— 发生在<b>下单</b>时。用户已经点了「提交订单」，
     *       前端要做的是<b>刷新购物车</b>让他看到最新库存，因为刚刚
     *       很可能被别人买走了一部分</li>
     *   <li>1008 加购超限 —— 发生在<b>购物车</b>里。用户还在挑东西，
     *       前端要做的是<b>把数量输入框改回一个合法值</b>，
     *       页面其他部分不用动</li>
     * </ul>
     *
     * <p>判断标准依然是 {@link #USERNAME_TAKEN} 注释里那条：
     * <b>「前端需不需要针对它做不同的动作」</b>。
     */
    public static final int CART_QUANTITY_LIMIT = 1008;

    /**
     * 分类的层级不合法（★ 里程碑 16 起）。
     *
     * <p>三种情况共用这一个码，因为它们对前端来说是<b>同一件事</b>：
     * 「你这个上级分类选得不对，换一个」——
     * 前端要做的是把「上级分类」选择器标红，不需要区分是哪种。
     * <pre>
     *   1. 把自己设成自己的上级            （自环）
     *   2. 挂到一个已经有上级的分类下面     （会变成三级）
     *   3. 一个有子分类的分类想挂到别人下面 （会成环，也会把子分类顶成三级）
     * </pre>
     *
     * <p><b>为什么要有这个码，而不是干脆允许三级？</b>
     *
     * <p>因为前端只画两级（顶部导航 → 左侧栏 / 商品表单的分类选择器）。
     * 后端如果接受三级，商家在后台建出「手机 → 手机壳 → 硅胶壳」，
     * 用户在商城页只看得到前两级 —— <b>第三级凭空消失，而且没有任何一层会报错</b>。
     * 这是本项目最忌讳的那类失败：数据没坏、页面少东西、没人知道。
     * </p>
     *
     * <p><b>一条会报错的规则，胜过一片会消失的分类。</b>
     * 所以这里是明确拒绝（400 性质的业务错误），不是静默截断。
     * 要把分类做到三级，得同时改后端规则、两端的渲染和测试，那是一件独立的事。
     */
    public static final int CATEGORY_LEVEL_INVALID = 1009;

    /**
     * 上级分类不存在，或者已禁用（★ 里程碑 16 起）。
     *
     * <p>和 {@link #CATEGORY_LEVEL_INVALID}（1009）分开，判断标准还是
     * 「前端需不需要针对它做不同的动作」：
     * <ul>
     *   <li>1009 层级不对 —— 用户选了一个<b>能看见但用不了</b>的上级，
     *       提示是「不能挂在这一级下面」</li>
     *   <li>1010 上级无效 —— 用户选中的那个上级<b>根本不在合法集合里</b>
     *       （已经不存在，或者被禁用了），提示是「这个上级分类已不可用，请重新选」，
     *       而且前端接下来该做的是<b>刷新选择器的选项</b></li>
     * </ul>
     *
     * <p>「父分类必须启用」这条容易被当成洁癖，其实它的症状很具体：
     * 一个新商品挂进「被禁用的父分类」下面，它在商城页<b>既不是根、
     * 也不出现在任何根的子树里</b>，于是从导航里彻底消失 ——
     * 而商品本身还是上架的。用户只会以为「这件东西没了」。
     */
    public static final int CATEGORY_PARENT_INVALID = 1010;

    /**
     * 分类下还有子分类，不能删除（★ 里程碑 16 起）。
     *
     * <p><b>为什么不复用 {@link #CATEGORY_HAS_PRODUCT}（1004）？</b>
     * 因为提示语里的<b>名词</b>不一样，用户要采取的动作也不一样：
     * 1004 说的是「还有 N 个<b>商品</b>，请先移走或删除这些商品」，
     * 1011 说的是「还有 N 个<b>子分类</b>，请先删除这些子分类」。
     * 共用一个码，前端就只能显示一句含糊的「该分类下还有东西」。
     *
     * <p><b>为什么在 Service 里拦，而不是靠数据库？</b>
     * 全库零外键是既定约定（见 README），所以数据库<b>不会</b>阻止
     * 「删掉父分类、子分类还指着它」。留下的脏数据不会报错：
     * 那些子分类的 {@code parent_id} 指向一个不存在的 id，
     * 于是它们既不是根、也不在任何根的子树里 ——
     * <b>从商城导航里消失，而库里还在、商品还挂着</b>。
     * 这是最难查的一类 bug，所以必须在删除前拦住。
     *
     * <p>★ 检查顺序：<b>先查子分类（1011），后查商品（1004）</b>。
     * 结构性问题（还有挂在它下面的分类）优先于内容性问题（还有商品）。
     */
    public static final int CATEGORY_HAS_CHILD = 1011;

    // ======================================================================
    //  ★ 里程碑 17：售后相关的三个码
    //
    //  它们三个有一个共同点，也是它们区别于 1002 的地方：
    //  ★★ 前端收到它们时要做的是**把那一行标记成某个状态、并去掉入口**，
    //    而不是「弹一句错误提示」。弹提示要求用户「看到提示之后自己
    //    去把那行找出来」，而这三件事的正确反馈是**就地改变那一行的样子**。
    //  这正是 ResultCode.USERNAME_TAKEN 注释里那条判据：
    //  「前端需不需要针对它做不同的动作」。
    // ======================================================================

    /**
     * 这条订单明细已经有<b>进行中</b>的售后单了（★ 里程碑 17）。
     *
     * <p>什么时候返回：申请售后时撞上了 {@code uk_order_item_active} 唯一索引
     * （或者预检查发现已经有一张 {@code status ∈ {0,1,2}} 的单）。
     *
     * <p><b>★ 前端不要为它弹错误框。</b>正常路径下用户根本看不到它 ——
     * 按钮在那行已经有售后单时就不显示了。它出场的场景是
     * 「用户开了两个标签页，在一个里面申请了，在另一个里面又点了一次」，
     * 那时候的正确反馈是<b>把那一行刷新成「处理中」并显示已有的售后单号</b>。
     */
    public static final int AFTER_SALE_EXISTS = 1012;

    /**
     * 这条订单明细<b>已经退过款</b>了，不能再申请售后 / 不能再评价（★ 里程碑 17）。
     *
     * <p>什么时候返回：
     * <pre>
     *   申请售后 → 这一行有一张 status = 3 的售后单
     *   发表评价 → 同上（见 ProductReviewServiceImpl.create 的判断顺序）
     * </pre>
     *
     * <p><b>★ 为什么和 {@link #AFTER_SALE_EXISTS}（1012）分开？</b>
     * 因为前端要做的事不一样：1012 是「等一等，在处理中」，
     * 1013 是「这件事已经结束了，入口永远去掉」。共用一个码的话，
     * 前端只能显示一句含糊的「不能申请」，用户会以为过几天还能再试。
     *
     * <p>★ 为什么不复用 {@link #ORDER_STATUS_INVALID}（1002）？
     * 因为订单状态不对时前端要做的是「重查订单列表」（订单的状态变了），
     * 而这里的订单状态可能是完全正常的 —— 变的是<b>那一行</b>。
     */
    public static final int ORDER_ITEM_REFUNDED = 1013;

    /**
     * 已经超过售后申请期限（★ 里程碑 17）。
     *
     * <p>什么时候返回：订单是「已完成」，而 {@code complete_time} 距今
     * 超过了 {@code mall.order.after-sale-window-days} 天。
     *
     * <p><b>★ 注意它只可能出现在「已完成」的订单上</b> ——
     * 已付款（未发货）和已发货（未收货）的订单没有 {@code complete_time}，
     * 也就没有「起点」，所以不受时限约束。
     * 结构上这是唯一可能的选择：起点是「确认收货」，
     * 而未确认收货的订单根本没有这个起点。
     * （业务上也是对的：钱在商家手里、货还在路上，
     *   不该因为「等太久」剥夺用户退款的权利。）
     *
     * <p>★ 前端收到它要做的是<b>把那一行的「申请售后」入口去掉</b>，
     * 并显示一句「已过售后期限」—— 而不是弹一个错误框
     * （用户并没有做错什么，是时间过了）。
     *
     * <p>★ 这个码几乎不会被真的返回：前端拿的是服务端给的
     * {@code afterSaleDeadline}（一个绝对时刻），过期的行根本不会显示入口。
     * 它的存在是为了<b>让服务端的不变量不依赖前端</b> ——
     * 绕过页面直接调接口时，这里仍然会拦住。
     */
    public static final int AFTER_SALE_EXPIRED = 1014;
}
